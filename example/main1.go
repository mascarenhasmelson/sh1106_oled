// cmd/monitor/main.go — System stats monitor on SH1106 128×64 OLED
//
// Displays:
//   Row 0  │ IP: 192.168.1.42
//   Row 1  │ CPU: 0.12LA        48.3'C
//   Row 2  │ Mem: 0.4/3.7GB 12.3%
//   Row 3  │ Disk: 4/29GB 14%
//
// Build:
//   GOARCH=arm64 GOOS=linux go build -o monitor ./cmd/monitor
//
// Run:
//   ./monitor

package main

import (
	"fmt"
	"log"
	"os/exec"
	"strings"
	"time"

	"sh1106/sh1106"
)

const (
	loopTime  = time.Second
	i2cBus    = 1
	i2cAddr   = 0x3C
	rowHeight = 16 // pixels per text row (matches 8px font × 2 scale, or adjust)
)

// ---------------------------------------------------------------------------
// stat helpers — mirror the Python subprocess calls exactly
// ---------------------------------------------------------------------------

func shell(cmd string) string {
	out, err := exec.Command("sh", "-c", cmd).Output()
	if err != nil {
		return "N/A"
	}
	return strings.TrimSpace(string(out))
}

func getIP() string {
	return "IP: " + shell("hostname -I | cut -d' ' -f1")
}

func getCPU() string {
	return shell("top -bn1 | grep load | awk '{printf \"CPU: %.2f\", $(NF-2)}'") + "LA"
}

func getTemp() string {
	// Raspberry Pi: vcgencmd measure_temp → temp=48.3'C
	t := shell("vcgencmd measure_temp 2>/dev/null | cut -f2 -d'='")
	if t == "" || t == "N/A" {
		// Fallback: /sys/class/thermal (works on most Linux SBCs)
		raw := shell("cat /sys/class/thermal/thermal_zone0/temp 2>/dev/null")
		if raw != "" && raw != "N/A" {
			var milli int
			fmt.Sscanf(raw, "%d", &milli)
			t = fmt.Sprintf("%.1f'C", float64(milli)/1000.0)
		}
	}
	return t
}

func getMem() string {
	// "used_GB total_GB percent"
	parts := strings.Fields(
		shell("free -m | awk 'NR==2{printf \"%.1f %.1f %.1f\", $3/1024,$2/1024,($3/$2)*100}'"),
	)
	if len(parts) != 3 {
		return "Mem: N/A"
	}
	return fmt.Sprintf("Mem:%s/%sGB %s%%", parts[0], parts[1], parts[2])
}

func getDisk() string {
	return shell("df -h | awk '$NF==\"/\"{printf \"Disk: %d/%dGB %s\", $3,$2,$5}'")
}

// ---------------------------------------------------------------------------
// Scaled text — the built-in font is 5×8; we double it to 10×16 so it fills
// the 128×64 display nicely with 4 rows at rowHeight=16.
// ---------------------------------------------------------------------------

// drawStringScaled draws text at pixel (x,y) scaled by sx,sy.
func drawStringScaled(d *sh1106.Device, x, y int, s string, sx, sy int) {
	cx := x
	for _, ch := range []byte(s) {
		drawCharScaled(d, cx, y, ch, sx, sy)
		cx += 6 * sx
		if cx+6*sx > sh1106.Width128 {
			break
		}
	}
}

// drawCharScaled draws one character with pixel scaling.
func drawCharScaled(d *sh1106.Device, x, y int, ch byte, sx, sy int) {
	if ch < 0x20 || ch > 0x7E {
		ch = '?'
	}
	glyph := font5x8[ch-0x20]
	for col := 0; col < 5; col++ {
		colData := glyph[col]
		for row := 0; row < 8; row++ {
			on := colData&(1<<uint(row)) != 0
			for dx := 0; dx < sx; dx++ {
				for dy := 0; dy < sy; dy++ {
					d.SetPixel(x+col*sx+dx, y+row*sy+dy, on)
				}
			}
		}
	}
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

func main() {
	conn, err := sh1106.NewLinuxI2CConn(i2cBus, i2cAddr)
	if err != nil {
		log.Fatalf("open i2c: %v", err)
	}
	defer conn.Close()

	d := sh1106.New(conn, sh1106.Width128, sh1106.Height64)
	if err := d.Init(); err != nil {
		log.Fatalf("init display: %v", err)
	}

	log.Println("SH1106 monitor started")

	for {
		ip := getIP()
		cpu := getCPU()
		temp := getTemp()
		mem := getMem()
		disk := getDisk()

		d.Clear()

		// Row 0 — IP  (scale 1×2: 5-wide font, 16px tall)
		drawStringScaled(d, 0, 0, ip, 1, 2)

		// Row 1 — CPU left, Temp right
		drawStringScaled(d, 0, 16, cpu, 1, 2)
		// Right-align temp: each char is 6px wide at scale 1
		tempX := sh1106.Width128 - len(temp)*6
		if tempX < 0 {
			tempX = 0
		}
		drawStringScaled(d, tempX, 16, temp, 1, 2)

		// Row 2 — Memory
		drawStringScaled(d, 0, 32, mem, 1, 2)

		// Row 3 — Disk
		drawStringScaled(d, 0, 48, disk, 1, 2)

		if err := d.Display(); err != nil {
			log.Printf("display error: %v", err)
		}

		time.Sleep(loopTime)
	}
}

